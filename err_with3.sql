DDEPARTMENTColumns
CREATE DATABASE company;
USE company;

-- 2. DEPARTMENT tablosu (Döngüsel bağımlılığı önlemek için önce FK'sız oluşturulur)
CREATE TABLE DEPARTMENT (
    DNAME VARCHAR(50) NOT NULL,
    DNUMBER INT PRIMARY KEY,
    MGRSSN CHAR(9),
    MGRSTARTDATE DATE
);

-- 3. EMPLOYEE tablosu
CREATE TABLE EMPLOYEE (
    FNAME VARCHAR(15) NOT NULL,
    MINIT CHAR(1),
    LNAME VARCHAR(15) NOT NULL,
    SSN CHAR(9) PRIMARY KEY,
    BDATE DATE,
    ADDRESS VARCHAR(50),
    SEX CHAR(1),
    SALARY DECIMAL(10,2),
    SUPERSSN CHAR(9),
    DNO INT,
    FOREIGN KEY (SUPERSSN) REFERENCES EMPLOYEE(SSN),
    FOREIGN KEY (DNO) REFERENCES DEPARTMENT(DNUMBER)
);

-- 4. DEPARTMENT tablosunun yönetici (MGRSSN) bağlantısını ekle
ALTER TABLE DEPARTMENT
